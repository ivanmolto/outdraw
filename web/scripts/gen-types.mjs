// Generate types/schemas.ts from /shared/schemas and types/limits.ts from
// /shared/limits.json. Never hand-edit the output.
//
// Each schema file becomes a `$defs` entry of one bundled schema, so cross-file refs
// (`Score.schema.json#/$defs/ScoreBreakdown`) resolve to a single module. Every `$defs`
// name must be unique across files.
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const WEB_DIR = join(dirname(fileURLToPath(import.meta.url)), "..");
const SCHEMAS_DIR = join(WEB_DIR, "..", "shared", "schemas");
const OUTPUT = join(WEB_DIR, "types", "schemas.ts");
const LIMITS_INPUT = join(WEB_DIR, "..", "shared", "limits.json");
const LIMITS_OUTPUT = join(WEB_DIR, "types", "limits.ts");
const SUFFIX = ".schema.json";

function rewriteRef(ref) {
  const [file, pointer] = ref.split("#");
  return pointer ? `#${pointer}` : `#/$defs/${file.slice(0, -SUFFIX.length)}`;
}

function rewrite(node) {
  if (Array.isArray(node)) return node.map(rewrite);
  if (node && typeof node === "object") {
    return Object.fromEntries(
      Object.entries(node).map(([k, v]) => [
        k,
        k === "$ref" && typeof v === "string" ? rewriteRef(v) : rewrite(v),
      ]),
    );
  }
  return node;
}

function bundle() {
  const defs = {};
  const files = readdirSync(SCHEMAS_DIR)
    .filter((f) => f.endsWith(SUFFIX))
    .sort();
  for (const file of files) {
    const { $schema, $id, $defs = {}, ...schema } = JSON.parse(
      readFileSync(join(SCHEMAS_DIR, file), "utf8"),
    );
    void $schema;
    void $id;
    const hoisted = { [file.slice(0, -SUFFIX.length)]: schema, ...$defs };
    for (const [name, definition] of Object.entries(hoisted)) {
      if (name in defs) throw new Error(`duplicate $defs name across schema files: ${name}`);
      defs[name] = rewrite(definition);
    }
  }
  return { title: ROOT_TITLE, $defs: defs };
}

const ROOT_TITLE = "OutdrawSchemas";
// The bundle root is a codegen artefact, not a type anyone should import.
const ROOT_INTERFACE = `\nexport interface ${ROOT_TITLE} {\n  [k: string]: unknown;\n}\n`;

const ts = await compile(bundle(), ROOT_TITLE, {
  bannerComment: "// Generated by scripts/gen-types.mjs from /shared/schemas. Do not edit.",
  unreachableDefinitions: true,
  additionalProperties: false,
});
if (!ts.includes(ROOT_INTERFACE)) throw new Error("bundle root interface not found in output");
writeFileSync(OUTPUT, ts.replace(ROOT_INTERFACE, ""));
console.log("wrote types/schemas.ts");

// /shared is outside the Turbopack root (next.config.ts pins it to /web), so the limits
// are copied into the package as a module instead of imported from the JSON.
const limits = Object.entries(JSON.parse(readFileSync(LIMITS_INPUT, "utf8"))).filter(
  ([k]) => !k.startsWith("$"),
);
writeFileSync(
  LIMITS_OUTPUT,
  [
    "// Generated by scripts/gen-types.mjs from /shared/limits.json. Do not edit.",
    "",
    "/** Input bounds shared with the agent (agent/draw/limits.py). */",
    "export const SHARED_LIMITS = {",
    ...limits.map(([k, v]) => `  ${k}: ${JSON.stringify(v)},`),
    "} as const;",
    "",
  ].join("\n"),
);
console.log("wrote types/limits.ts");
