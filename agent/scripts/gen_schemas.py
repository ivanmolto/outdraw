"""Generate draw/schemas.py (Pydantic v2) from /shared/schemas. Never hand-edit the output.

Each schema file becomes a `$defs` entry of one bundled schema, so cross-file refs
(`Score.schema.json#/$defs/ScoreBreakdown`) resolve to a single module. Every `$defs`
name must be unique across files.
"""

from __future__ import annotations

import json
import subprocess
import sys
import tempfile
from pathlib import Path
from typing import Any

AGENT_DIR = Path(__file__).resolve().parents[1]
SCHEMAS_DIR = AGENT_DIR.parent / "shared" / "schemas"
OUTPUT = AGENT_DIR / "draw" / "schemas.py"
SUFFIX = ".schema.json"
ROOT_TITLE = "OutdrawSchemas"
ROOT_ALIAS = f'type {ROOT_TITLE} = Annotated[Any, Field(title="{ROOT_TITLE}")]\n\n'


def _rewrite_ref(ref: str) -> str:
    file, _, pointer = ref.partition("#")
    if pointer:
        return f"#{pointer}"
    return f"#/$defs/{file.removesuffix(SUFFIX)}"


def _rewrite(node: Any) -> Any:
    if isinstance(node, dict):
        return {
            k: _rewrite_ref(v) if k == "$ref" and isinstance(v, str) else _rewrite(v)
            for k, v in node.items()
        }
    if isinstance(node, list):
        return [_rewrite(v) for v in node]
    return node


def bundle() -> dict[str, Any]:
    defs: dict[str, Any] = {}
    for path in sorted(SCHEMAS_DIR.glob(f"*{SUFFIX}")):
        schema = json.loads(path.read_text())
        name = path.name.removesuffix(SUFFIX)
        hoisted = {name: schema, **schema.pop("$defs", {})}
        for key in ("$schema", "$id"):
            schema.pop(key, None)
        for def_name, definition in hoisted.items():
            if def_name in defs:
                raise SystemExit(f"duplicate $defs name across schema files: {def_name}")
            defs[def_name] = _rewrite(definition)
    return {
        "$schema": "https://json-schema.org/draft/2020-12/schema",
        "title": ROOT_TITLE,
        "$defs": defs,
    }


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        bundled = Path(tmp) / "outdraw.schema.json"
        bundled.write_text(json.dumps(bundle(), indent=2))
        subprocess.run(
            [
                sys.executable,
                "-m",
                "datamodel_code_generator",
                "--input",
                str(bundled),
                "--input-file-type",
                "jsonschema",
                "--output",
                str(OUTPUT),
                "--output-model-type",
                "pydantic_v2.BaseModel",
                "--target-python-version",
                "3.12",
                "--use-title-as-name",
                "--use-standard-collections",
                "--use-union-operator",
                "--use-double-quotes",
                "--field-constraints",
                "--use-annotated",
                "--enum-field-as-literal",
                "all",
                "--use-type-alias",
                "--formatters",
                "ruff-format",
                "ruff-check",
                "--disable-timestamp",
                "--custom-file-header",
                "# Generated by scripts/gen_schemas.py from /shared/schemas. Do not edit.",
            ],
            check=True,
        )
    # The bundle root is a codegen artefact, not a type anyone should import.
    generated = OUTPUT.read_text()
    if ROOT_ALIAS not in generated:
        raise SystemExit("bundle root alias not found in generated output")
    OUTPUT.write_text(generated.replace(ROOT_ALIAS, ""))
    print(f"wrote {OUTPUT.relative_to(AGENT_DIR)}")


if __name__ == "__main__":
    main()
